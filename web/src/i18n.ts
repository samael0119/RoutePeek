export type MessageKey = keyof typeof messages.zh;

export function tFor(locale: Locale, key: MessageKey, vars: Record<string, string | number> = {}): string {
  let value = messages[locale][key] ?? messages.zh[key] ?? key;
  for (const [name, replacement] of Object.entries(vars)) {
    value = value.replaceAll(`{${name}}`, String(replacement));
  }
  return value;
}

const currentLocale = ref<Locale>('zh');

export function useI18n() {
  const locale = currentLocale;

  function t(key: MessageKey, vars: Record<string, string | number> = {}): string {
    return tFor(locale.value, key, vars);
  }

  function toggleLocale() {
    locale.value = locale.value === 'zh' ? 'en' : 'zh';
  }

  return { locale, t, toggleLocale };
}
